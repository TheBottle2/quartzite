export function detectDefaultLang(): Lang {
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return (['tr', 'en', 'de', 'fr', 'es'] as Lang[]).includes(nav as Lang) ? (nav as Lang) : 'en';
}

